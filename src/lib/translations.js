const patternRules = [
  {
    en: /^CONFIRMED VOLUNTEERS \((\d+)\)$/,
    bn: /^নিশ্চিত স্বেচ্ছাসেবক \((\d+)\)$/,
    toBn: (match) => `নিশ্চিত স্বেচ্ছাসেবক (${match[1]})`,
    toEn: (match) => `CONFIRMED VOLUNTEERS (${match[1]})`,
  },
  {
    en: /^See All Members \((\d+)\)$/,
    bn: /^সব সদস্য দেখুন \((\d+)\)$/,
    toBn: (match) => `সব সদস্য দেখুন (${match[1]})`,
    toEn: (match) => `See All Members (${match[1]})`,
  },
  {
    en: /^Joined (.+)$/,
    bn: /^(.+) যোগদান করেছেন$/,
    toBn: (match) => `${match[1]} যোগদান করেছেন`,
    toEn: (match) => `Joined ${match[1]}`,
  },
];

const bnToEn = Object.fromEntries(
  Object.entries(enToBn).map(([english, bengali]) => [bengali, english])
);

const originalTexts = new WeakMap();
const originalAttributes = new WeakMap();
const translatedAttributes = ["placeholder", "title", "alt", "aria-label"];
let activeObserver = null;

function lookup(text, toBn) {
  const dictionary = toBn ? enToBn : bnToEn;
  if (dictionary[text]) return dictionary[text];

  for (const rule of patternRules) {
    const match = text.match(toBn ? rule.en : rule.bn);
    if (match) return (toBn ? rule.toBn : rule.toEn)(match);
  }

  return null;
}

function translateTextNode(node, toBn) {
  if (!node || node.nodeType !== 3) return;

  const raw = node.nodeValue;
  if (typeof raw !== "string") return;

  const trimmed = raw.trim();
  if (!trimmed) return;

  if (!toBn) {
    const original = originalTexts.get(node);
    if (original) {
      node.nodeValue = raw.replace(trimmed, original);
      originalTexts.delete(node);
      return;
    }
  }

  const replacement = lookup(trimmed, toBn);
  if (!replacement || replacement === trimmed) return;

  if (toBn) originalTexts.set(node, trimmed);
  node.nodeValue = raw.replace(trimmed, replacement);
}

function translateElement(element, toBn) {
  if (!element || element.nodeType !== 1) return;
  if (element.hasAttribute("data-no-translate")) return;
  if (["SCRIPT", "STYLE", "NOSCRIPT"].includes(element.tagName)) return;

  let stored = originalAttributes.get(element);
  if (!stored) {
    stored = new Map();
    originalAttributes.set(element, stored);
  }

  for (const attribute of translatedAttributes) {
    const value = element.getAttribute(attribute);
    if (!value) continue;

    const trimmed = value.trim();
    if (!trimmed) continue;

    if (!toBn && stored.has(attribute)) {
      element.setAttribute(attribute, value.replace(trimmed, stored.get(attribute)));
      stored.delete(attribute);
      continue;
    }

    const replacement = lookup(trimmed, toBn);
    if (!replacement || replacement === trimmed) continue;

    if (toBn) stored.set(attribute, value);
    element.setAttribute(attribute, value.replace(trimmed, replacement));
  }
}

function translateSubtree(root, toBn) {
  if (!root || typeof Node === "undefined") return;

  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root, toBn);
    return;
  }

  const isElement = root.nodeType === Node.ELEMENT_NODE;
  const isFragment =
    root.nodeType === Node.DOCUMENT_FRAGMENT_NODE ||
    root.nodeType === Node.DOCUMENT_NODE;
  if (!isElement && !isFragment) return;
  if (isElement) translateElement(root, toBn);

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
    {
      acceptNode(node) {
        if (
          node.nodeType === Node.ELEMENT_NODE &&
          (node.hasAttribute("data-no-translate") ||
            ["SCRIPT", "STYLE", "NOSCRIPT"].includes(node.tagName))
        ) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    }
  );

  let node;
  while ((node = walker.nextNode())) {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, toBn);
    else translateElement(node, toBn);
  }
}

export function applyDomTranslation(language) {
  if (typeof document === "undefined") return;

  const toBn = language === "bn";
  stopDomTranslation();
  translateSubtree(document.body, toBn);

  if (!toBn) return;

  activeObserver = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "childList") {
        mutation.addedNodes.forEach((node) => translateSubtree(node, toBn));
      } else if (mutation.type === "characterData") {
        translateTextNode(mutation.target, toBn);
      } else if (mutation.type === "attributes") {
        translateElement(mutation.target, toBn);
      }
    }
  });

  activeObserver.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: translatedAttributes,
  });
}

export function stopDomTranslation() {
  if (activeObserver) {
    activeObserver.disconnect();
    activeObserver = null;
  }
}
